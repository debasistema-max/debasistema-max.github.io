import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { describe, it } from 'node:test';

describe('reconexão segura do OneDrive', () => {
  it('guarda o refresh token no Vault e limita acesso ao backend', () => {
    const migration = readFileSync(new URL('../supabase/migrations/0020_onedrive_vault_connection.sql', import.meta.url), 'utf8');
    assert.match(migration, /vault\.create_secret/);
    assert.match(migration, /vault\.update_secret/);
    assert.match(migration, /revoke all on function public\.backend_get_onedrive_refresh_token\(\) from public, anon, authenticated/);
    assert.match(migration, /grant execute on function public\.backend_set_onedrive_refresh_token\(text\) to service_role/);
  });

  it('conclui device code no backend sem devolver tokens ao navegador', () => {
    const syncFunction = readFileSync(new URL('../supabase/functions/sync-onedrive/index.ts', import.meta.url), 'utf8');
    const main = readFileSync(new URL('../src/main.js', import.meta.url), 'utf8');
    const api = readFileSync(new URL('../src/services/api.js', import.meta.url), 'utf8');
    assert.match(syncFunction, /connect_start/);
    assert.match(syncFunction, /connect_complete/);
    assert.match(syncFunction, /authorization_pending/);
    assert.match(syncFunction, /backend_set_onedrive_refresh_token/);
    assert.match(syncFunction, /\["microsoft\.com", "www\.microsoft\.com"\]/);
    assert.match(syncFunction, /\["\/devicelogin", "\/link"\]/);
    assert.doesNotMatch(main, /refresh_token/);
    assert.match(main, /Reconectar OneDrive/);
    assert.match(main, /Confirmar conexão/);
    assert.match(api, /response\.clone\(\)\.text\(\)/);
    assert.match(api, /JSON\.parse\(body\)/);
    assert.match(api, /throw await invocationError\(error\)/);
  });

  it('atualiza somente a matriz configurada após criar backup', () => {
    const syncFunction = readFileSync(new URL('../supabase/functions/sync-onedrive/index.ts', import.meta.url), 'utf8');
    const patchScript = readFileSync(new URL('../scripts/patch-matrix-remote.mjs', import.meta.url), 'utf8');
    const patchWorkbook = readFileSync(new URL('../scripts/patch-matrix-workbook.py', import.meta.url), 'utf8');
    const workflow = readFileSync(new URL('../.github/workflows/sync-catalog.yml', import.meta.url), 'utf8');
    const main = readFileSync(new URL('../src/main.js', import.meta.url), 'utf8');
    const api = readFileSync(new URL('../src/services/api.js', import.meta.url), 'utf8');
    assert.match(syncFunction, /offline_access Files\.ReadWrite/);
    assert.match(syncFunction, /input\.action === "patch_matrix"/);
    assert.match(syncFunction, /queueMatrixPatch\(user\.id, input\.rows \|\| \[\]\)/);
    assert.match(syncFunction, /matrix_patch: "true"/);
    assert.match(syncFunction, /input\.action === "prepare_matrix_upload"/);
    assert.match(syncFunction, /createUploadSession/);
    assert.match(syncFunction, /uploadUrl\.protocol !== "https:"/);
    assert.match(syncFunction, /uploadUrl\.username \|\| uploadUrl\.password/);
    assert.match(syncFunction, /upload_url: rawUploadUrl/);
    assert.doesNotMatch(syncFunction, /hostname\.endsWith\("\.up\.1drv\.com"\)/);
    assert.match(syncFunction, /rows\.length > 200/);
    assert.match(syncFunction, /"codigo_ips"/);
    assert.match(syncFunction, /requiredEnv\("ONEDRIVE_FOLDER_PATH"\)/);
    assert.match(syncFunction, /requiredEnv\("ONEDRIVE_WORKBOOK_NAME"\)/);
    assert.match(syncFunction, /const BACKUP_FOLDER_NAME = "Backup DebaPortal"/);
    assert.match(syncFunction, /await ensureBackupFolder\(token, target\.folderId\)/);
    assert.match(syncFunction, /"@microsoft\.graph\.conflictBehavior": "fail"/);
    assert.match(syncFunction, /const backupName = await createWorkbookBackup\(token, target\)/);
    assert.match(syncFunction, /parentReference: \{ driveId: target\.driveId, id: backupFolderId \}/);
    assert.match(syncFunction, /const backupUrl = `\$\{GRAPH_ROOT\}\/items\/\$\{encodeURIComponent\(backupFolderId\)\}:\/\$\{encodeURIComponent\(backupName\)\}/);
    assert.match(syncFunction, /Number\(backup\.size\) === expectedSize/);
    assert.doesNotMatch(syncFunction, /new URL\(location\)/);
    assert.match(syncFunction, /const sourceRows = new Map<string, number\[\]>\(\)/);
    assert.match(syncFunction, /usedRange\(valuesOnly=true\)\?%24select=rowIndex,columnIndex,rowCount,columnCount/);
    assert.match(syncFunction, /const codeChunkSize = 20_000/);
    assert.match(syncFunction, /%24select=values/);
    assert.doesNotMatch(syncFunction, /usedRange\(valuesOnly=true\)\?%24select=values,rowIndex/);
    assert.match(syncFunction, /Cadastro Item SAP/);
    assert.match(syncFunction, /const rowsNeedingSap = missingRows\.filter/);
    assert.match(syncFunction, /rowsNeedingSap\.length\s*\? loadSapMatrixDefaults/);
    assert.match(syncFunction, /findMatrixTable/);
    assert.match(syncFunction, /workbook\/tables\/\$\{encodeURIComponent\(table\.id\)\}\/rows\/add/);
    assert.match(syncFunction, /body: JSON\.stringify\(\{ index: null, values \}\)/);
    assert.match(syncFunction, /addMatrixRangeRows/);
    assert.match(syncFunction, /cloneMatrixRowStyle/);
    assert.match(syncFunction, /formulasR1C1/);
    assert.match(syncFunction, /A formatacao auxiliar nao pode impedir a inclusao dos dados/);
    assert.doesNotMatch(syncFunction, /format\/borders/);
    assert.doesNotMatch(syncFunction, /MATRIZ precisa estar formatada como tabela do Excel/);
    assert.match(syncFunction, /rows_added: rowsAdded/);
    assert.match(syncFunction, /appendDataValues/);
    assert.match(syncFunction, /const updates = sanitized\.flatMap/);
    assert.match(syncFunction, /sheet_rows_updated: updates\.length/);
    assert.match(syncFunction, /backup_folder: BACKUP_FOLDER_NAME/);
    assert.match(syncFunction, /const RETRYABLE_BATCH_STATUS = new Set\(\[408, 409, 423, \.\.\.RETRYABLE_STATUS\]\)/);
    assert.match(syncFunction, /for \(let attempt = 0; attempt < 4 && pending\.length; attempt \+= 1\)/);
    assert.match(syncFunction, /retry\.push\(pending\[index\]\)/);
    assert.match(syncFunction, /start \+= 10/);
    assert.match(syncFunction, /await applyWorkbookUpdates\(token, itemId, sheetName, updates\.slice\(start, start \+ 10\)\)/);
    assert.match(syncFunction, /workbook\/worksheets\/\$\{sheetName\}\/range/);
    assert.ok(syncFunction.indexOf('await createWorkbookBackup(token, target)') < syncFunction.indexOf('await applyWorkbookUpdates(token, itemId, sheetName'));
    assert.match(api, /body: \{ action: 'patch_matrix', rows \}/);
    assert.match(main, /driveResult\?\.backup_folder/);
    assert.ok(main.indexOf('await api.patchMatrixOneDrive') < main.indexOf("await api.importRows('catalog', `partial-matrix:"));
    assert.match(main, /Reconectar OneDrive/);
    assert.match(main, /Atualização da MATRIZ solicitada/);
    assert.match(main, /job\.summary\?\.operation === 'MATRIX_PATCH'/);
    assert.match(workflow, /matrix_patch:/);
    assert.match(workflow, /patch-matrix-remote\.mjs/);
    assert.match(workflow, /openpyxl==3\.1\.5/);
    assert.match(patchScript, /action: "prepare_matrix_upload"/);
    assert.match(patchScript, /Content-Range/);
    assert.match(patchScript, /RETRYABLE_UPLOAD_STATUS = new Set\(\[423, 429, 500, 502, 503, 504\]\)/);
    assert.match(patchScript, /response\.headers\.get\("retry-after"\)/);
    assert.match(patchScript, /attempt < 7/);
    assert.match(patchScript, /await uploadWorkbook\(uploadUrl, outputBytes\)/);
    assert.match(patchScript, /A planilha permaneceu bloqueada no OneDrive/);
    assert.match(patchScript, /parsePortalWorkbook/);
    assert.match(patchWorkbook, /copy_row_template/);
    assert.match(patchWorkbook, /extend_filters_and_tables/);
  });
});
